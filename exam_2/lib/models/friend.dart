class Friend {
  final String name;
  final String status;
  final String device;
  final String section;
  final bool isPlaying;
  final bool isOnline;
  final bool isRead;

  const Friend({
    required this.name,
    required this.status,
    required this.device,
    required this.section,
    required this.isPlaying,
    required this.isOnline,
    required this.isRead,
  });
}
